import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import {
  DIRECTORY_NAME,
  INJECT_SCRIPT_TAG_ID,
  JSON_FILE_NAME,
} from '@plugin-web-update-notification/core'
import type { Options } from '@plugin-web-update-notification/core'
import { rspack } from '@rspack/core'
import type { RspackOptions, Stats } from '@rspack/core'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { WebUpdateNotificationPlugin } from './index'

let dir: string
let outputPath: string

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), 'pwun-rspack-'))
  outputPath = join(dir, 'dist')
  writeFileSync(join(dir, 'entry.js'), 'console.log(1)')
  // stands in for the index.html that HtmlRspackPlugin writes during a build
  mkdirSync(outputPath)
  writeFileSync(join(outputPath, 'index.html'), '<html><head></head><body></body></html>')
})

afterEach(() => {
  rmSync(dir, { recursive: true, force: true })
})

function createCompiler(mode: RspackOptions['mode'], options: Options = {}) {
  return rspack({
    mode,
    context: dir,
    entry: './entry.js',
    output: { path: outputPath },
    plugins: [
      new WebUpdateNotificationPlugin({ versionType: 'custom', customVersion: 'v1', ...options }),
    ],
  })
}

function run(mode: RspackOptions['mode'], options?: Options) {
  const compiler = createCompiler(mode, options)
  return new Promise<Stats | undefined>((resolve, reject) => {
    compiler.run((err, stats) => {
      compiler.close(() => (err ? reject(err) : resolve(stats)))
    })
  })
}

/** Runs one watch build, then stops watching. */
function watchOnce(mode: RspackOptions['mode']) {
  const compiler = createCompiler(mode)
  return new Promise<void>((resolve, reject) => {
    const watching = compiler.watch({}, (err) => {
      watching.close(() => (err ? reject(err) : resolve()))
    })
  })
}

function injectCount() {
  const html = readFileSync(join(outputPath, 'index.html'), 'utf8')
  return html.split(`data-id="${INJECT_SCRIPT_TAG_ID}"`).length - 1
}

const versionJsonPath = () => join(outputPath, DIRECTORY_NAME, `${JSON_FILE_NAME}.json`)

describe('rspack plugin', () => {
  it('injects into index.html and emits version.json in production mode', async () => {
    await run('production')
    expect(injectCount()).toBe(1)
    expect(existsSync(versionJsonPath())).toBe(true)
  })

  it('does not minify the injected script again', async () => {
    const stats = await run('production', { logVersion: false })
    const script = stats!
      .toJson({ assets: true })
      .assets!.find(
        (asset) => asset.name.endsWith('.js') && asset.name.startsWith(`${DIRECTORY_NAME}/`),
      )!
    const content = readFileSync(join(outputPath, script.name), 'utf8')
    // the source generated by the plugin, untouched by the minimizer
    expect(content).toContain('window.__checkUpdateSetup__({"versionType":"custom"')
  })

  it('still runs when mode is not set, since rspack builds that as production', async () => {
    await run(undefined)
    expect(injectCount()).toBe(1)
  })

  it('does nothing in development mode', async () => {
    await run('development')
    expect(injectCount()).toBe(0)
    expect(existsSync(versionJsonPath())).toBe(false)
  })

  it('does nothing in watch mode, even with mode production', async () => {
    await watchOnce('production')
    expect(injectCount()).toBe(0)
    expect(existsSync(versionJsonPath())).toBe(false)
  })
})
